const WRITE_VERBS = /^(Add|Apply|Batch|Block|Checkout|Clear|Connect|Consume|Continue|Copy|Create|Decline|Delete|Exchange|Follow|Force|Generate|Issue|Join|Leave|Like|List2Cart|Login|Mark|Modify|Navigate|Post|Provide|Quick|React|Read|Redeem|Refuse|Remove|Report|Save|Send|Set|Suggest|Swap|Switch|Sync|UnConsume|Unblock|Undelete|Unfollow|Update|Use|Validate|Parse)/;
const READ_ALLOWED = new Set(['CheckUsername', 'CheckUserExists', 'IsIndexed', 'IsMealPlanPartSavedAsTemplate', 'HasSamsungAccountLinked']);

test('all 240 method names are classified; no mutating verb is ever a read', () => {
  assert.equal(new Set(ALL_METHODS).size, ALL_METHODS.length);
  for (const m of ALL_METHODS) {
    const verb = m.slice(m.lastIndexOf('/') + 1);
    if (WRITE_VERBS.test(verb)) assert.equal(isReadMethod(m), false, `${m} mutates and must not be a read`);
    if (/^(Get|Search|Autocomplete|Analyze|Recommend|Extract)/.test(verb)) assert.equal(isReadMethod(m), true, `${m} should be a read`);
    if (READ_ALLOWED.has(verb)) assert.equal(isReadMethod(m), true, m);
  }
});

test('previously misclassified methods are writes', () => {
  for (const verb of ['RetailerAPI/CheckoutList', 'RetailerAPI/CheckoutCart', 'FoodpediaAPI/SuggestChange', 'AuthAPI/IssueAuthCode']) {
    const full = ALL_METHODS.find((m) => m.endsWith(verb));
    assert.ok(full, `${verb} missing from list`);
    assert.equal(isReadMethod(full), false, verb);
  }
});
