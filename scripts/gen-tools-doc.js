#!/usr/bin/env node
/**
 * Generates docs/tools.md from the tool definitions in src/tools/.
 * Works offline: it only imports the definitions and never builds a client,
 * reads a token or touches the network.
 *
 *   node scripts/gen-tools-doc.js          write docs/tools.md
 *   node scripts/gen-tools-doc.js --check  exit 1 if docs/tools.md is out of date
 */

import fs from 'node:fs';
import { TOOLS, TOOL_AREAS, toolAccess, toolArea } from '../src/tools/index.js';
import { toJsonSchema } from '../src/tools/schema.js';

const OUT = new URL('../docs/tools.md', import.meta.url);

const ORDER = ['Meal plan', 'Weekly templates', ...TOOL_AREAS.map((a) => a[0]).filter((h) => h !== 'Meal plan' && h !== 'Weekly templates')];

function typeOf(p) {
  if (p.enum) return p.enum.map((v) => `\`${v}\``).join(' | ');
  if (p.const !== undefined) return `\`${JSON.stringify(p.const)}\``;
  if (p.anyOf || p.oneOf) return [...new Set((p.anyOf ?? p.oneOf).map(typeOf))].join(' | ');
  if (p.type === 'array') return `${typeOf(p.items ?? {})}[]`;
  return p.type ?? 'any';
}

const cell = (s) => String(s ?? '').replace(/\s*\n\s*/g, ' ').replace(/\|/g, '\\|');

function constraints(p) {
  const c = [];
  if (p.minimum !== undefined) c.push(`min ${p.minimum}`);
  if (p.exclusiveMinimum !== undefined) c.push(`> ${p.exclusiveMinimum}`);
  if (p.maximum !== undefined) c.push(`max ${p.maximum}`);
  if (p.minLength !== undefined && p.minLength > 1) c.push(`min length ${p.minLength}`);
  if (p.maxLength !== undefined) c.push(`max length ${p.maxLength}`);
  if (p.minItems !== undefined) c.push(`min ${p.minItems} items`);
  if (p.maxItems !== undefined) c.push(`max ${p.maxItems} items`);
  return c;
}

function render() {
  const byArea = new Map(ORDER.map((h) => [h, []]));
  for (const t of TOOLS) {
    byArea.get(toolArea(t.name)).push(t);
  }

  const counts = { 'read-only': 0, write: 0, destructive: 0 };
  for (const t of TOOLS) counts[toolAccess(t)]++;

  const out = [];
  out.push(
    '# Tool reference',
    '',
    '<!-- Generated by scripts/gen-tools-doc.js from src/tools/. Do not edit by hand; run `npm run docs:tools`. -->',
    '',
    `The MCP server exposes ${TOOLS.length} tools: ${counts['read-only']} read-only, ${counts.write} write and ${counts.destructive} destructive.`,
    '',
    '| Flag | Meaning | MCP annotations |',
    '|---|---|---|',
    '| read-only | Reads data only. | `readOnlyHint: true` |',
    '| write | Creates or changes data, removes nothing. | `readOnlyHint: false`, `destructiveHint: false` |',
    '| destructive | Can delete or overwrite data. | `destructiveHint: true` |',
    '',
    'All tools validate their input strictly: unknown parameters are rejected, IDs must look like IDs',
    'returned by other tools, dates are real `YYYY-MM-DD` calendar dates, and list sizes are capped.',
    'Results come back as JSON text plus `structuredContent`; output longer than 40000 characters is',
    'truncated with a hint to narrow the request. Failures are returned as `isError` results.',
    'Parameters marked "yes" under Required must be given; the others are optional.',
    '',
    'Write and destructive tools change the real account, including shared lists and meal plans.',
    '',
    '## Contents',
    ''
  );
  for (const h of ORDER) {
    const list = byArea.get(h);
    if (list.length) out.push(`- [${h}](#${h.toLowerCase().replace(/[^a-z0-9 ]/g, '').replace(/ /g, '-')}) (${list.length}): ${list.map((t) => `[\`${t.name}\`](#${t.name})`).join(', ')}`);
  }
  out.push('');

  for (const h of ORDER) {
    const list = byArea.get(h);
    if (!list.length) continue;
    out.push(`## ${h}`, '');
    for (const t of list) {
      out.push(`### \`${t.name}\``, '', `**${toolAccess(t)}**${t.annotations.idempotentHint && !t.annotations.readOnlyHint ? ', idempotent' : ''}`, '', cell(t.description), '');
      const js = toJsonSchema(t.schema);
      const props = Object.entries(js.properties);
      if (props.length) {
        const req = new Set(js.required ?? []);
        out.push('| Parameter | Type | Required | Description |', '|---|---|---|---|');
        for (const [name, p] of props) {
          const extra = [...constraints(p), ...(p.default !== undefined ? [`default ${JSON.stringify(p.default)}`] : [])];
          const desc = [cell(p.description), extra.length ? `(${extra.join(', ')})` : ''].filter(Boolean).join(' ');
          out.push(`| \`${name}\` | ${cell(typeOf(p))} | ${req.has(name) ? 'yes' : 'no'} | ${desc} |`);
        }
        out.push('');
      } else {
        out.push('No parameters.', '');
      }
      out.push('Example arguments:', '', '```json', JSON.stringify(t.example ?? {}), '```', '');
    }
  }
  return `${out.join('\n').trimEnd()}\n`;
}

const text = render();
if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== text) {
    console.error('docs/tools.md is out of date. Run: npm run docs:tools');
    process.exit(1);
  }
  console.log('docs/tools.md is up to date.');
} else {
  fs.writeFileSync(OUT, text);
  console.log(`Wrote docs/tools.md (${TOOLS.length} tools).`);
}
