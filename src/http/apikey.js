/**
 * API key for the local HTTP API: generated once, stored in the config dir (chmod 600),
 * overridable with SAMSUNG_FOOD_API_KEY. Compared in constant time.
 */

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { CONFIG_DIR } from '../core/auth.js';
import { writeFileAtomic } from '../core/fsutil.js';

export const API_KEY_FILE = path.join(CONFIG_DIR, 'api-key');

/** Keys shorter than this are refused (also for the env override). */
const MIN_KEY_LENGTH = 16;

/**
 * Returns `{ key, source, created }`; source is 'env' or 'file'. `created` is true only when
 * the key was generated by this call, so the caller can print it once.
 */
export function loadOrCreateApiKey({ file = API_KEY_FILE, env = process.env } = {}) {
  const fromEnv = env.SAMSUNG_FOOD_API_KEY?.trim();
  if (fromEnv) {
    if (fromEnv.length < MIN_KEY_LENGTH) throw new Error(`SAMSUNG_FOOD_API_KEY must be at least ${MIN_KEY_LENGTH} characters`);
    return { key: fromEnv, source: 'env', created: false };
  }
  try {
    const stored = fs.readFileSync(file, 'utf8').trim();
    if (stored.length >= MIN_KEY_LENGTH) return { key: stored, source: 'file', created: false };
  } catch (err) {
    if (err.code !== 'ENOENT') throw err;
  }
  const key = `sfk_${crypto.randomBytes(32).toString('base64url')}`;
  writeFileAtomic(file, `${key}\n`);
  return { key, source: 'file', created: true };
}

const digest = (v) => crypto.createHash('sha256').update(String(v)).digest();

/** Constant-time comparison (hashing first makes the lengths equal). */
export function keyMatches(given, expected) {
  if (typeof given !== 'string' || !given) return false;
  return crypto.timingSafeEqual(digest(given), digest(expected));
}

/** The key from `Authorization: Bearer <key>`, or null. */
export function bearerToken(header) {
  const m = /^Bearer\s+(\S+)\s*$/i.exec(header ?? '');
  return m ? m[1] : null;
}
